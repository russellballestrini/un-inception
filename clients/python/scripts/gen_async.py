# ---- 2. replace whole top-level functions by name
def replace_functions(text, mapping):
    tree = ast.parse(text)
    lines = text.splitlines(keepends=True)
    spans = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name in mapping:
            first = (node.decorator_list[0].lineno if node.decorator_list else node.lineno) - 1
            spans.append((first, node.end_lineno, mapping[node.name]))
    missing = set(mapping) - {n.name for n in tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))}
    assert not missing, missing
    for first, last, new in sorted(spans, reverse=True):
        lines[first:last] = [new.rstrip("\n") + "\n"] if new else []
    return "".join(lines)


