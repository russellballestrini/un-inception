# ---- 5. make functions async where they await, transitively; await their calls
def asyncify(text):
    tree = ast.parse(text)
    for node in ast.walk(tree):
        for child in ast.iter_child_nodes(node):
            child._parent = node

    funcs = [n for n in ast.walk(tree) if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))]

    def own_nodes(fn):
        stack = list(ast.iter_child_nodes(fn))
        while stack:
            n = stack.pop()
            yield n
            if not isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda)):
                stack.extend(ast.iter_child_nodes(n))

    def handed_to_runner(call):
        parent = getattr(call, "_parent", None)
        return (isinstance(parent, ast.Call) and isinstance(parent.func, ast.Attribute)
                and parent.func.attr == "run" and getattr(parent.func.value, "id", None) == "asyncio")

    def is_async_call(n):
        return (isinstance(n, ast.Call) and isinstance(n.func, ast.Name)
                and n.func.id in async_names and not handed_to_runner(n))

    async_names = set()
    for fn in funcs:
        if isinstance(fn, ast.AsyncFunctionDef) or any(
                isinstance(n, (ast.Await, ast.AsyncFor, ast.AsyncWith)) for n in own_nodes(fn)):
            async_names.add(fn.name)
    changed = True
    while changed:
        changed = False
        for fn in funcs:
            if fn.name in async_names:
                continue
            for n in own_nodes(fn):
                if is_async_call(n):
                    async_names.add(fn.name)
                    changed = True
                    break

    edits = []  # (line, col_bytes, text)
    for fn in funcs:
        if isinstance(fn, ast.FunctionDef) and fn.name in async_names:
            edits.append((fn.lineno, fn.col_offset, "async "))
    for n in ast.walk(tree):
        if is_async_call(n):
            parent = getattr(n, "_parent", None)
            if isinstance(parent, ast.Await):
                continue
            needs_parens = (
                (isinstance(parent, ast.Attribute) and parent.value is n)
                or (isinstance(parent, ast.Subscript) and parent.value is n)
                or (isinstance(parent, ast.Call) and parent.func is n)
            )
            if needs_parens:
                edits.append((n.lineno, n.col_offset, "(await "))
                edits.append((n.end_lineno, n.end_col_offset, ")"))
            else:
                edits.append((n.lineno, n.col_offset, "await "))

    lines = [line.encode("utf-8") for line in text.splitlines(keepends=True)]
    for line, col, ins in sorted(edits, key=lambda e: (e[0], e[1]), reverse=True):
        b = lines[line - 1]
        lines[line - 1] = b[:col] + ins.encode() + b[col:]
    return b"".join(lines).decode("utf-8"), async_names


