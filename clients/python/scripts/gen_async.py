    payload = body.encode("utf-8") if body and method != "GET" else None
    signed_body = body if payload else ""

    def headers_for(timestamp: int) -> Dict[str, str]:
        return {
            "Authorization": f"Bearer {public_key}",
            "X-Timestamp": str(timestamp),
            "X-Signature": _sign_request(secret_key, timestamp, method, path, signed_body),
            "Content-Type": "application/json",
        }

    response = await _http(method, url, headers=headers_for(int(time.time())), data=payload)

    # Handle 428 sudo OTP challenge
    if response.status_code == 428:
        try:
            challenge_id = response.json().get("challenge_id", "")
        except (ValueError, KeyError, AttributeError):
            challenge_id = ""

        print("\\033[33mConfirmation required. Check your email for a one-time code.\\033[0m", file=sys.stderr)
